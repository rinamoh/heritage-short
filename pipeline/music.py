"""Music stage: plan cue times from the timeline, and import candidates generated on Kaggle.

The score itself is generated by kaggle/music_acestep.ipynb. Nothing here calls a model.
"""

import json
from pathlib import Path
from typing import Any

from pipeline.common import config
from pipeline.narration import measure_duration_ffprobe
from pipeline.timeline import ShotTiming, build_timeline, subtitle_cue_times

MAX_SHORT_BY_S: float = 2.0
KAGGLE_LOG_NAME: str = "runs_kaggle.jsonl"


def _load(storyboard_path: Path) -> dict[str, Any]:
    """Read storyboard.json."""
    return json.loads(storyboard_path.read_text(encoding="utf-8"))


def _save_music(storyboard_path: Path, music: dict[str, Any]) -> None:
    """Rewrite only the "music" block of storyboard.json, leaving the rest as typed."""
    raw = storyboard_path.read_bytes().decode("utf-8")
    newline = "\r\n" if "\r\n" in raw else "\n"
    text = raw.replace("\r\n", "\n")
    start = text.index("{", text.index('\n  "music":'))
    _, end = json.JSONDecoder().raw_decode(text, start)
    block = json.dumps(music, indent=2, ensure_ascii=False).replace("\n", "\n  ")
    text = text[:start] + block + text[end:]
    storyboard_path.write_bytes(text.replace("\n", newline).encode("utf-8"))


def cue_times(
    cues: list[dict[str, Any]],
    timeline: list[ShotTiming],
    end_card_s: float,
) -> list[dict[str, Any]]:
    """Give every cue the in and out time of the shots it covers ("end" is the end card)."""
    total_s = sum(shot.length_s for shot in timeline)
    spans = {shot.shot_id: (shot.start_s, shot.start_s + shot.length_s) for shot in timeline}
    spans["end"] = (total_s, total_s + end_card_s)
    timed: list[dict[str, Any]] = []
    for cue in cues:
        unknown = [shot_id for shot_id in cue["shots"] if shot_id not in spans]
        if unknown:
            raise ValueError(f"Music cue {cue['id']} names unknown shot(s): {', '.join(unknown)}")
        in_s = min(spans[shot_id][0] for shot_id in cue["shots"])
        out_s = max(spans[shot_id][1] for shot_id in cue["shots"])
        timed.append({**cue, "in_s": round(in_s, 3), "out_s": round(out_s, 3)})
    return timed


def plan_music(storyboard_path: Path = config.STORYBOARD_PATH) -> None:
    """Compute cue times and music.duration_s, save them, and print the cue table."""
    storyboard = _load(storyboard_path)
    narration_dir = config.stage_output_dir("narration", create=False)
    timeline = build_timeline(storyboard, narration_dir, allow_estimates=True)
    end_card_s = float(storyboard["output"]["end_card_s"])
    total_s = round(sum(shot.length_s for shot in timeline) + end_card_s, 3)

    music = storyboard["music"]
    music["cues"] = cue_times(music["cues"], timeline, end_card_s)
    music["duration_s"] = total_s
    _save_music(storyboard_path, music)

    estimated = [s.shot_id for s in timeline if any(seg.estimated for seg in s.segments)]
    print("\nShot lengths:")
    for shot in timeline:
        note = " (estimate)" if shot.shot_id in estimated else ""
        print(f"  {shot.shot_id:4} {shot.start_s:6.2f} + {shot.length_s:5.2f}s{note}")
    print("\nCue   In (s)  Out (s)  Shots            Music")
    for cue in music["cues"]:
        shots = ",".join(cue["shots"])
        print(f"{cue['id']:4} {cue['in_s']:7.2f} {cue['out_s']:8.2f}  {shots:15}  {cue['description']}")
    print(f"\nTotal film length (music.duration_s): {total_s:.2f}s, end card included")
    if not 60.0 <= total_s <= 90.0:
        print(f"[WARN] {total_s:.2f}s is outside 60-90s")

    for shot, timing in zip(storyboard["shots"], timeline):
        if len(shot.get("subtitle_en") or []) > 1:
            print(f"\nSubtitle cues for {timing.shot_id} (split by text length):")
            for begin, end, lines in subtitle_cue_times(shot, timing):
                print(f"  {begin:6.2f}-{end:6.2f}  {' / '.join(lines)}")

    print("\nValues for the notebook's config cell:")
    print(f"CAPTION = {music['caption']!r}")
    print(f"BPM = {music['bpm']}\nKEY = {music['key']!r}")
    print(f"DURATION_S = {total_s}\nSEEDS = {music['seeds']}")
    if estimated:
        print(
            f"\n[ESTIMATE] No narration yet for {', '.join(estimated)}. "
            "Run music-plan again after narration, before generating music."
        )


def _append_kaggle_log(source: Path, log_path: Path) -> int:
    """Append Kaggle log lines to runs.jsonl, skipping lines that are already there."""
    if not source.is_file():
        print(f"No {source.name} in {source.parent}; nothing to add to runs.jsonl.")
        return 0
    seen: set[str] = set()
    existing = log_path.read_text(encoding="utf-8") if log_path.is_file() else ""
    for line in existing.splitlines():
        if line.strip():
            seen.add(json.dumps(json.loads(line), sort_keys=True))
    new_lines: list[str] = []
    for line in source.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        entry = json.loads(line)
        key = json.dumps(entry, sort_keys=True)
        if key not in seen:
            seen.add(key)
            new_lines.append(json.dumps(entry, ensure_ascii=False))
    if new_lines:
        separator = "" if not existing or existing.endswith("\n") else "\n"
        with log_path.open("a", encoding="utf-8") as handle:
            handle.write(separator + "\n".join(new_lines) + "\n")
    return len(new_lines)


def import_music(
    choose: int | None = None,
    storyboard_path: Path = config.STORYBOARD_PATH,
    music_dir: Path | None = None,
    log_path: Path = config.RUNS_LOG_PATH,
) -> None:
    """Check downloaded candidates, merge their log lines, list them, and optionally choose one."""
    storyboard = _load(storyboard_path)
    music = storyboard["music"]
    folder = music_dir if music_dir is not None else config.stage_output_dir("music")
    wanted_s = float(music["duration_s"])

    added = _append_kaggle_log(folder / KAGGLE_LOG_NAME, log_path)
    print(f"Added {added} Kaggle line(s) to {log_path.name}.")

    if choose is not None:
        if not (folder / f"music_{choose}.wav").is_file():
            raise FileNotFoundError(f"Cannot choose {choose}: {folder / f'music_{choose}.wav'} is missing")
        music["chosen"] = choose
        _save_music(storyboard_path, music)

    for seed in music["seeds"]:
        path = folder / f"music_{seed}.wav"
        if not path.is_file():
            print(f"  seed {seed}: missing ({path.name})")
            continue
        length_s = measure_duration_ffprobe(path)
        mark = "  <- chosen" if music.get("chosen") == seed else ""
        print(f"  seed {seed}: {path.name} {length_s:.2f}s (film {wanted_s:.2f}s){mark}")
        if wanted_s - length_s > MAX_SHORT_BY_S:
            print(f"  [WARN] seed {seed} is {wanted_s - length_s:.2f}s shorter than the film")
